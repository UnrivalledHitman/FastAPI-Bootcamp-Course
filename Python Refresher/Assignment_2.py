"""
Ask the user how many days until their birthday
- Using the print()function. Print an approx. number of weeks until their birthday
- 1 week is = to 7 days.
"""

# SourceCode

days_until_birthday = int(input("No. of days until their birthday:-  "))
weeks_until_birthday = days_until_birthday / 7

print(f"{weeks_until_birthday:.2f} weeks until your birthday !!!")
